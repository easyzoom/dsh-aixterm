// scripts/build-client.mjs — bundle src/client into lib/client.js in DSH's
// __ModuleLoader__ format. React is external (the web shell provides it);
// @xterm/* is bundled; xterm's CSS is imported as text and injected at runtime.
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(root, "lib/client.js");

const result = await build({
  entryPoints: [path.join(root, "src/client/index.jsx")],
  bundle: true,
  format: "cjs",
  platform: "browser",
  target: "es2020",
  jsx: "automatic",
  external: ["react", "react/jsx-runtime"],
  loader: { ".css": "text" },
  define: { "process.env.NODE_ENV": '"production"' },
  write: false,
  logLevel: "info",
});

const js = result.outputFiles[0].text;
const wrapped =
  "/* dsh-aixterm — generated by scripts/build-client.mjs; do not edit by hand. */\n" +
  "window.__ModuleLoader__.load({\n" +
  "  id: \"dsh-aixterm\",\n" +
  "  factory: (require) => {\n" +
  "    var module = { exports: {} };\n" +
  "    var exports = module.exports;\n" +
  "    Object.defineProperty(exports, Symbol.toStringTag, { value: \"Module\" });\n" +
  js +
  "\n    return module.exports;\n" +
  "  }\n" +
  "});\n";

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, wrapped, "utf8");
console.log("wrote", outFile, `(${wrapped.length} bytes)`);
